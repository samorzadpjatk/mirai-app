/**
 * GraphQL SDK Client for Seed App
 *
 * Uses the generated graphql-request SDK for type-safe API calls.
 * Authenticates with service account token.
 *
 * @module graphql-client
 */

import { GraphQLClient } from "graphql-request";
import { env } from "./env";

// =============================================================================
// GraphQL Endpoint Configuration
// =============================================================================

const GRAPHQL_ENDPOINT = env.graphqlEndpoint;

// =============================================================================
// Service Account Authentication
// =============================================================================

/**
 * Service account authentication header
 * Uses Supabase service role key for internal service access
 */
const getAuthHeaders = (): Record<string, string> => {
  return {
    Authorization: `Bearer ${env.serviceRoleKey}`,
    "X-Service-Account": "seed",
  };
};

// =============================================================================
// GraphQL Client
// =============================================================================

/**
 * Typed GraphQL client for seed operations
 * Configured with service account authentication
 */
export const seedGraphQLClient = new GraphQLClient(GRAPHQL_ENDPOINT, {
  headers: getAuthHeaders(),
});

// =============================================================================
// SDK Factory
// =============================================================================

let sdk: ReturnType<typeof createSeedSDK> | null = null;

/**
 * Create or get the GraphQL SDK instance
 * Lazy initialization for SDK
 */
export const getSeedSDK = (): ReturnType<typeof createSeedSDK> => {
  if (!sdk) {
    sdk = createSeedSDK();
  }
  return sdk;
};

/**
 * Reset the SDK (e.g., on auth failure)
 */
export const resetSeedSDK = (): void => {
  sdk = null;
};

// SDK will be imported from @mirai-app/graphql-types
// The getSdk function will be generated by graphql-codegen
import { getSdk } from "@mirai-app/graphql-types/sdk";

/**
 * Create SDK instance with configured client
 */
function createSeedSDK() {
  return getSdk(seedGraphQLClient);
}

// =============================================================================
// Type Exports
// =============================================================================

export type SeedSDK = ReturnType<typeof getSeedSDK>;

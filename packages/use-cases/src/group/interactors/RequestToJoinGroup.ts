import { Effect } from "effect";
import { GroupJoinRequest } from "@mirai-app/domain";
import { GroupPort } from "../ports/GroupPort";
import { TripParticipantPort } from "../../user/ports/TripParticipantPort";
import { GroupJoinRequestPort } from "../ports/GroupJoinRequestPort";
import type { GroupJoinRequestDTO } from "../dto/GroupDTOs";
import type { DatabaseError } from "@mirai-app/domain";
import {
  GroupNotFoundError,
  AlreadyInGroupError,
  JoinRequestAlreadyExistsError,
  NotTripParticipantError,
  TripHasEndedError,
} from "../errors/GroupErrors";

/**
 * Input for RequestToJoinGroupUseCase
 */
export interface RequestToJoinGroupInput {
  groupId: string;
  userId: string;
}

/**
 * Request To Join Group Use Case
 *
 * Creates a join request for a user to join a group.
 */
export class RequestToJoinGroupUseCase {
  execute(
    input: RequestToJoinGroupInput,
  ): Effect.Effect<
    GroupJoinRequestDTO,
    | DatabaseError
    | GroupNotFoundError
    | AlreadyInGroupError
    | JoinRequestAlreadyExistsError
    | NotTripParticipantError
    | TripHasEndedError,
    GroupPort | TripParticipantPort | GroupJoinRequestPort
  > {
    return Effect.gen(function* () {
      const groupPort = yield* GroupPort;
      const participantPort = yield* TripParticipantPort;
      const joinRequestPort = yield* GroupJoinRequestPort;

      // Find the group
      const group = yield* groupPort.findById(input.groupId);

      if (!group || group.isDeleted) {
        return yield* Effect.fail(
          new GroupNotFoundError({ groupId: input.groupId }),
        );
      }

      // Check if user is a trip participant
      const participant = yield* participantPort.findByUserAndTrip(
        input.userId,
        group.tripId,
      );

      if (!participant) {
        return yield* Effect.fail(
          new NotTripParticipantError({
            userId: input.userId,
            tripId: group.tripId,
          }),
        );
      }

      // Check if user is already in a group
      if (participant.groupId) {
        return yield* Effect.fail(
          new AlreadyInGroupError({
            userId: input.userId,
            groupId: participant.groupId,
          }),
        );
      }

      // Check for existing join request
      const existingRequest = yield* joinRequestPort.findByUserAndTrip(
        input.userId,
        group.tripId,
      );

      if (existingRequest) {
        if (existingRequest.groupId === group.id) {
          return yield* Effect.fail(
            new JoinRequestAlreadyExistsError({
              userId: input.userId,
              tripId: group.tripId,
            }),
          );
        } else {
          return yield* Effect.fail(
            new JoinRequestAlreadyExistsError({
              userId: input.userId,
              tripId: group.tripId,
            }),
          );
        }
      }

      // Create join request
      const requestEffect = GroupJoinRequest.create({
        id: "", // Will be generated by DB
        groupId: group.id,
        tripId: group.tripId,
        userId: input.userId,
        status: "PENDING",
        requestedAt: new Date(),
        decidedAt: null,
        decidedBy: null,
      });

      const request = yield* requestEffect;
      const createdRequest = yield* joinRequestPort.create(request);

      return {
        id: createdRequest.id,
        groupId: createdRequest.groupId,
        tripId: createdRequest.tripId,
        userId: createdRequest.userId,
        user: {
          id: input.userId,
          firstName: "", // Will be hydrated
          lastName: "",
          email: null,
        },
        status: createdRequest.status,
        requestedAt: createdRequest.requestedAt,
        decidedAt: createdRequest.decidedAt,
        decidedBy: null,
      };
    });
  }
}

import { printSchema } from "graphql";
import type { GraphQLSchema } from "graphql";
import { writeFile } from "fs/promises";
import { mkdir } from "fs/promises";
import { dirname } from "path";

/**
 * Schema output configuration
 */
export interface SchemaOutputConfig {
  /**
   * Output file path
   */
  path: string;

  /**
   * Include descriptions
   * @default true
   */
  includeDescriptions?: boolean;

  /**
   * Sort fields alphabetically
   * @default false
   */
  sort?: boolean;

  /**
   * Comment header
   */
  header?: string;
}

/**
 * Print a schema to SDL (Schema Definition Language) string
 *
 * @param schema - GraphQL schema
 * @param config - Output configuration
 * @returns SDL string
 */
export function printSchemaToSDL(
  schema: GraphQLSchema,
  config: Omit<SchemaOutputConfig, "path"> = {},
): string {
  const { includeDescriptions = true, header } = config;

  let sdl = printSchema(schema);

  if (header) {
    const headerComment = header
      .split("\n")
      .map((line) => (line.startsWith("#") ? line : `# ${line}`))
      .join("\n");
    sdl = `${headerComment}\n\n${sdl}`;
  }

  if (!includeDescriptions) {
    // Remove description comments (lines starting with ")
    sdl = sdl.replace(/"""[\s\S]*?"""/g, "");
  }

  return sdl;
}

/**
 * Write a schema to a file as SDL
 *
 * @param schema - GraphQL schema
 * @param config - Output configuration
 */
export async function writeSchemaToFile(
  schema: GraphQLSchema,
  config: SchemaOutputConfig,
): Promise<void> {
  const sdl = printSchemaToSDL(schema, config);

  // Ensure directory exists
  const dir = dirname(config.path);
  await mkdir(dir, { recursive: true });

  // Write schema file
  await writeFile(config.path, sdl, "utf-8");
}

/**
 * Generate schema file with default path
 *
 * @param schema - GraphQL schema
 * @param outputDir - Output directory
 * @returns Path to generated file
 */
export async function generateSchemaFile(
  schema: GraphQLSchema,
  outputDir: string = "./schema",
): Promise<string> {
  const path = `${outputDir}/schema.graphql`;
  const header = `
# Generated GraphQL Schema
# Do not edit this file directly
# Generated at: ${new Date().toISOString()}
`.trim();

  await writeSchemaToFile(schema, {
    path,
    header,
    includeDescriptions: true,
  });

  return path;
}
